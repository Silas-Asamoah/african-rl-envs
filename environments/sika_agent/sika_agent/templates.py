def relation(name: str, language: str) -> str:
    return RELATIONS[name]["en" if language == "en" else "tw"]


@functools.cache
def _phrasings() -> dict | None:
    if not PHRASINGS_FILE.exists():
        return None
    return json.loads(PHRASINGS_FILE.read_text(encoding="utf-8"))


def options(kind: str, name: str, language: str, split: str) -> list[str]:
    """The wordings a task in `split` may use: the generated pool, else the seeds.

    `kind` is "requests", "replies" or "injections"."""
    generated = _phrasings()
    if generated and (pool := generated[kind][name][language][split]):
        return pool
    seed = {"requests": REQUESTS, "replies": REPLIES, "injections": INJECTIONS}[kind][name][language]
    return seed if isinstance(seed, list) else [seed]
